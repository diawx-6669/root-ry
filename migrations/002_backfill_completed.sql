-- ============================================================
--  002 — перенос старого прогресса в модель знаний
--
--  До появления topic_mastery всё, что система знала о прогрессе,
--  лежало в users.completed_topics — плоском списке идентификаторов.
--  Эти ученики уже прошли темы, и обнулять их было бы нечестно.
--
--  Каждая пройденная тема заводится во второй коробке: ученик её
--  видел, но подтверждений в разные дни у нас нет, и считать её
--  освоенной (коробка 3+) не за что.
--
--  Срок повторения разносится на две недели вперёд хешем от названия
--  темы. Иначе ученик с 74 пройденными темами открыл бы приложение и
--  получил 74 просроченных повторения в один день — гарантированный
--  способ закрыть приложение и не вернуться.
--
--  Запускать один раз. Повторный запуск ничего не изменит:
--  ON CONFLICT DO NOTHING защищает уже перенесённые темы.
-- ============================================================

INSERT INTO topic_mastery (
    user_id, topic_id, box, streak_days, lapses,
    correct, total, due_on, last_seen, first_done, next_reward_on
)
SELECT
    u.id,
    t.topic_id,
    2,      -- тема пройдена, но не подтверждена повторениями
    0,
    0,
    0,      -- ответов по ней мы не сохраняли: считать не из чего
    0,
    CURRENT_DATE + (abs(hashtext(t.topic_id)) % 14),
    NULL,
    NULL,
    -- Награда за первое прохождение уже выдана когда-то раньше.
    -- Следующая — вместе с первым повторением, в тот же день.
    CURRENT_DATE + (abs(hashtext(t.topic_id)) % 14)
FROM users u
CROSS JOIN LATERAL jsonb_array_elements_text(u.completed_topics) AS t(topic_id)
WHERE jsonb_typeof(u.completed_topics) = 'array'
ON CONFLICT (user_id, topic_id) DO NOTHING;
