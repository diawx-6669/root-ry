-- ============================================================
--  004 — исследовательский контур
--
--  РКНП — конкурс научных проектов, а не выставка приложений.
--  Жюри спрашивает не «что вы сделали», а «откуда вы знаете, что
--  это работает». Ответить на это можно только цифрами, а цифры
--  надо собирать с первого дня эксперимента, а не вспоминать
--  за неделю до защиты.
--
--  Схема эксперимента простая и защитимая:
--    обе группы учатся по одним и тем же урокам;
--    у группы «А» включён контур повторения, у «Б» — нет;
--    обе пишут один и тот же тест до и после.
--  Разница в приросте между группами и есть результат.
-- ============================================================

-- Группа эксперимента.
--
-- Пусто = ученик в эксперименте не участвует. Это важнее, чем кажется:
-- случайный пользователь из интернета не должен попадать в выборку и
-- портить статистику.
--
--   'A' — полный продукт: интервальные повторения, тетрадь ошибок;
--   'B' — контроль: те же уроки, но без возвратов к пройденному.
ALTER TABLE users ADD COLUMN IF NOT EXISTS study_group TEXT;

-- Согласие на использование обезличенных данных в исследовании.
-- Без него ученик в выгрузку не попадает, даже если группа проставлена.
ALTER TABLE users ADD COLUMN IF NOT EXISTS research_consent BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_users_study_group
    ON users(study_group) WHERE study_group IS NOT NULL;

-- ── Замеры ───────────────────────────────────────────────────
-- Предтест и посттест на одном банке КСПОЯ. Банк из 120 вопросов,
-- в тест уходит случайная выборка 40 — два замера получаются одной
-- сложности, но разными вопросами, и запоминание заданий результат
-- не портит.
--
-- Ссылка на kspoya_sessions намеренно мягкая (без внешнего ключа):
-- замер должен пережить чистку старых сессий, иначе исследование
-- потеряет данные из-за обслуживания базы.
CREATE TABLE IF NOT EXISTS research_measurements (
    id          BIGSERIAL   PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- pre — до начала работы с продуктом, post — после.
    phase       TEXT        NOT NULL CHECK (phase IN ('pre', 'post')),
    session_id  TEXT,
    score       INTEGER     NOT NULL,
    total       INTEGER     NOT NULL,
    level       TEXT        NOT NULL,
    taken_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    -- Один замер каждой фазы на ученика: иначе «посттест» можно
    -- переписывать до нужного результата.
    UNIQUE (user_id, phase)
);

CREATE INDEX IF NOT EXISTS idx_research_measurements_user
    ON research_measurements(user_id);
