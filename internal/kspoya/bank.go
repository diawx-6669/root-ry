//
// Банк живёт ТОЛЬКО на сервере: правильные ответы и разборы никогда
// не попадают в браузер до завершения теста.
package kspoya

// Уровни сложности вопросов — от простого к сложному.
var Levels = []string{"A1", "A2", "B1", "B2", "C1", "C2"}

// OptionsPerQuestion — сколько вариантов ответа у каждого вопроса.
// Шесть вместо четырёх: вероятность угадать падает с 25% до 17%.
const OptionsPerQuestion = 6

// Question — один вопрос банка.
type Question struct {
	ID      int
	Level   string // A1..C2 — сложность вопроса
	Topic   string // раздел «дерева грамматики»
	Text    string
	Options []string // всегда 6 вариантов
	Correct int      // индекс правильного варианта, 0..5
	Explain string   // разбор, показывается ТОЛЬКО после завершения теста
}

func q(id int, level, topic, text string, options []string, correct int, explain string) Question {
	return Question{
		ID: id, Level: level, Topic: topic, Text: text,
		Options: options, Correct: correct, Explain: explain,
	}
}

