// Уровни сложности вопросов — от простого к сложному.
// Индекс в этом срезе используется как «вес» вопроса при подсчёте уровня.
var Levels = []string{"A1", "A2", "B1", "B2", "C1", "C2"}

// Question — один вопрос банка.
type Question struct {
	ID      int
	Level   string // A1..C2 — сложность вопроса
	Topic   string // раздел «дерева грамматики»
	Text    string
	Options []string // всегда 4 варианта
	Correct int      // индекс правильного варианта, 0..3
	Explain string   // разбор, показывается ТОЛЬКО после завершения теста
}

func q(id int, level, topic, text, a, b, c, d string, correct int, explain string) Question {
	return Question{
		ID: id, Level: level, Topic: topic, Text: text,
		Options: []string{a, b, c, d}, Correct: correct, Explain: explain,
	}
}

