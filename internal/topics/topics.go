// byID — индекс для быстрой проверки идентификатора.
var byID = func() map[string]Topic {
	m := make(map[string]Topic, len(All))
	for _, t := range All {
		m[t.ID] = t
	}
	return m
}()

// Get возвращает тему по идентификатору.
func Get(id string) (Topic, bool) {
	t, ok := byID[id]
	return t, ok
}

// Count — сколько всего тем в дереве.
func Count() int { return len(All) }

// ReviewXPPercent — какая доля награды выдаётся за повторение уже
// пройденной темы.
//
// Раньше повторное прохождение давало ноль: система отвечала «already_done»
// и на этом всё. Для игровой экономики это правильно, для обучения — ровно
// наоборот, потому что именно возвраты к теме и удерживают её в памяти.
//
// Сорок процентов — компромисс. Меньше, чем за первое прохождение, чтобы
// повторения не стали способом фармить XP вместо изучения нового; больше
// нуля, чтобы возвращаться было выгодно. Повторение засчитывается только
// когда тема просрочена по интервалу, так что повторить её десять раз за
// вечер и получить десять наград нельзя.
const ReviewXPPercent = 40

// ReviewReward — награда за повторение темы: XP и монеты.
//
// Округление вверх: у самых дешёвых тем (40 XP, 8 монет) сорок процентов
// от восьми монет — это 3.2, и округление вниз превратило бы награду в
// символические три монеты, а по монетам ещё и в ноль для будущих тем
// дешевле пяти.
func ReviewReward(t Topic) (xp, coins int) {
	return share(t.XP), share(t.Coins)
}

func share(v int) int {
	if v <= 0 {
		return 0
	}
	r := (v*ReviewXPPercent + 99) / 100
	if r < 1 {
		r = 1
	}
	return r
}
