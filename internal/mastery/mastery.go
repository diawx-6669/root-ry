// Package mastery — модель знаний ученика: когда возвращать его к теме.
//
// Реализован интервальный повтор по схеме Лейтнера. Тема лежит в одной из
// пяти «коробок», каждой коробке соответствует свой интервал. Ответил
// верно — тема поднимается на коробку выше и следующий раз всплывёт позже.
// Ошибся — падает в первую коробку и вернётся завтра.
//
// Почему Лейтнер, а не SM-2 или FSRS: он умещается в сорок строк, его
// поведение полностью предсказуемо и объясняется двумя предложениями. На
// школьном горизонте в четыре-шесть недель разница в удержании с более
// сложными алгоритмами неразличима, а вот отладить и защитить простую
// схему можно.
//
// Пакет намеренно не знает ни про базу, ни про HTTP: на вход состояние и
// ответ, на выход новое состояние. Поэтому его можно целиком покрыть
// тестами, не поднимая ничего.
package mastery

import "time"

// Intervals — сколько дней тема «отдыхает» после подъёма в коробку N.
// Индекс 0 соответствует первой коробке.
//
// Интервалы расширяющиеся, а не равные: кривая забывания Эббингауза
// падает круто в первые дни и полого дальше, поэтому первые повторения
// должны идти часто, а последующие — всё реже.
var Intervals = []int{1, 3, 7, 16, 35}

// MaxBox — номер последней коробки. Тема в ней считается освоенной,
// но всё равно возвращается раз в 35 дней: «навсегда выучено» не бывает.
var MaxBox = len(Intervals)

// PromoteAfterDays — сколько дней ВОЗВРАТА с верным ответом нужно, чтобы
// подняться на коробку выше.
//
// Считаются именно дни, а не ответы: восемь верных ответов за один вечер не
// значат ничего, ученик помнит правило, которое прочитал десять минут назад.
//
// День первого знакомства с темой в счёт не идёт вообще. Это учебное
// событие, а не проверка: ответ сразу после теории показывает не знание, а
// работу кратковременной памяти. Серия начинается со второго дня.
const PromoteAfterDays = 2

// State — что система знает о владении одной темой (или одним заданием).
//
// Нулевое значение — корректное состояние «тема ещё не изучалась».
type State struct {
	Box        int       // 1..MaxBox; 0 означает «темы ещё не касались»
	StreakDays int       // разных дней подряд с верным ответом
	Lapses     int       // сколько раз тема забывалась после освоения
	Correct    int       // верных ответов за всё время
	Total      int       // всего ответов
	DueOn      time.Time // дата следующего повторения
	LastSeen   time.Time // дата последнего ответа
	FirstDone  time.Time // дата первого прохождения темы
}

// Answer — что именно произошло при ответе на задание.
type Answer struct {
	Correct bool
	// Assisted — ответ дан после того, как ученик открыл полный разбор.
	//
	// Такой ответ не наказывается: посмотреть разбор и понять — нормальный
	// способ учиться. Но и подтверждением знания он быть не может: ученик
	// повторил то, что прочитал секунду назад. Поэтому серия не двигается,
	// коробка не растёт, и срок повторения остаётся прежним — тема
	// по-прежнему за учеником.
	//
	// Это единственный механизм, который делает подсказки честными. Если
	// бы подсказка просто снижала XP, выгоднее всего было бы открыть
	// разбор и получить чуть меньше монет; здесь же прогресс по теме
	// нужно заработать самому.
	Assisted bool
}

// Apply возвращает новое состояние после одного самостоятельного ответа.
//
// today передаётся снаружи, а не берётся из time.Now(): так функция
// остаётся чистой и тестируется на любых календарных сценариях.
func Apply(cur State, correct bool, today time.Time) State {
	return ApplyAnswer(cur, Answer{Correct: correct}, today)
}

// ApplyAnswer — то же самое, но с учётом того, открывал ли ученик разбор.
func ApplyAnswer(cur State, a Answer, today time.Time) State {
	correct := a.Correct
	today = day(today)
	next := cur
	next.Total++
	if correct {
		next.Correct++
	}

	// firstEncounter — ученик впервые открыл эту тему. День знакомства не
	// участвует в серии подтверждений: см. комментарий к PromoteAfterDays.
	firstEncounter := next.Box == 0
	if firstEncounter {
		next.Box = 1
		next.FirstDone = today
	}

	// Ответ с открытым разбором меняет только счётчики и дату последнего
	// касания. Ни коробка, ни серия, ни срок повторения не двигаются:
	// просроченная тема так и остаётся просроченной.
	if correct && a.Assisted {
		if firstEncounter {
			next.DueOn = today.AddDate(0, 0, intervalFor(next.Box))
		}
		next.LastSeen = today
		return next
	}

	switch {
	case !correct:
		// Ошибка обнуляет серию и роняет тему в первую коробку.
		// Lapses растёт только если тема уже была освоена: провал на
		// первом же знакомстве с темой — это не «забыл», а «ещё не знал».
		if cur.Box > 1 {
			next.Lapses++
		}
		next.Box = 1
		next.StreakDays = 0

	case firstEncounter || sameDay(cur.LastSeen, today):
		// Либо это день первого знакомства с темой, либо ученик отвечает
		// повторно в уже засчитанный день. Серию не двигаем — но и не
		// наказываем: переделывать задания в тот же день должно быть
		// безопасно, иначе работа над ошибками бьёт по старательным.

	default:
		next.StreakDays++
		if next.StreakDays >= PromoteAfterDays {
			if next.Box < MaxBox {
				next.Box++
			}
			next.StreakDays = 0
		}
	}

	next.LastSeen = today
	next.DueOn = today.AddDate(0, 0, intervalFor(next.Box))
	return next
}

// intervalFor — через сколько дней показывать тему из коробки box.
func intervalFor(box int) int {
	if box < 1 {
		box = 1
	}
	if box > MaxBox {
		box = MaxBox
	}
	return Intervals[box-1]
}

// IsDue сообщает, пора ли возвращать ученика к теме.
// Тема, которой не касались вообще, «просроченной» не считается —
// её сначала надо изучить, а не повторить.
func (s State) IsDue(today time.Time) bool {
	if s.Box == 0 {
		return false
	}
	return !day(s.DueOn).After(day(today))
}

// Overdue — на сколько дней просрочено повторение. Используется для
// сортировки плана на сегодня: самое забытое показываем первым.
func (s State) Overdue(today time.Time) int {
	if s.Box == 0 {
		return 0
	}
	d := int(day(today).Sub(day(s.DueOn)).Hours() / 24)
	if d < 0 {
		return 0
	}
	return d
}

// Strength — оценка владения темой от 0 до 1, для окраски узла дерева.
//
// Считается по коробке, а не по доле верных ответов: важно не сколько
// ученик угадал за всё время, а насколько давно он подтверждал знание.
// Просроченная тема теряет силу тем быстрее, чем меньше её интервал.
func (s State) Strength(today time.Time) float64 {
	if s.Box == 0 {
		return 0
	}
	base := float64(s.Box-1) / float64(MaxBox-1)
	if over := s.Overdue(today); over > 0 {
		decay := float64(over) / float64(intervalFor(s.Box))
		if decay > 1 {
			decay = 1
		}
		base *= 1 - 0.5*decay
	}
	return base
}

// Status — как показать тему в дереве.
type Status string

const (
	// StatusNew — тему ещё не открывали.
	StatusNew Status = "new"
	// StatusLearning — тема изучается, до освоения ещё далеко.
	StatusLearning Status = "learning"
	// StatusMastered — тема освоена и повторение пока не требуется.
	StatusMastered Status = "mastered"
	// StatusDue — пора повторить: узел в дереве выцветает.
	StatusDue Status = "due"
)

// MasteredBox — начиная с какой коробки тема считается освоенной.
// Третья коробка означает интервал в неделю: тема пережила два
// разнесённых по дням подтверждения, это уже не память о прочитанном.
const MasteredBox = 3

// Status возвращает состояние темы для дерева грамматики.
func (s State) Status(today time.Time) Status {
	switch {
	case s.Box == 0:
		return StatusNew
	case s.IsDue(today):
		return StatusDue
	case s.Box >= MasteredBox:
		return StatusMastered
	default:
		return StatusLearning
	}
}

// Resolved — закрыто ли задание для тетради ошибок.
//
// Задание уходит из тетради, когда ученик ответил верно в двух разных
// днях подряд. Тот же порог, что и для подъёма темы по коробкам, и по
// той же причине: ответ через минуту после разбора ничего не доказывает.
func (s State) Resolved() bool {
	return s.Box > 1 || s.StreakDays >= PromoteAfterDays
}

// day отбрасывает время, оставляя календарную дату в UTC.
func day(t time.Time) time.Time {
	if t.IsZero() {
		return t
	}
	y, m, d := t.Date()
	return time.Date(y, m, d, 0, 0, 0, 0, time.UTC)
}

// sameDay сравнивает две отметки по календарной дате.
func sameDay(a, b time.Time) bool {
	if a.IsZero() || b.IsZero() {
		return false
	}
	return day(a).Equal(day(b))
}
